"""
Day 8: Synthetic Golden Dataset E2E Regression Test Suite.

Focus:
- Loading synthetic ground-truth test cases generated by Synthesizer.
- Validating the live SUT (CustomerSupportRAGBot) against auto-generated benchmarks.
- Evaluating live answers using FaithfulnessMetric, ContextualRecallMetric, and AnswerRelevancyMetric.
- Verifying synthetic dataset schema integrity.
"""

import json
from pathlib import Path
import pytest
from deepeval import assert_test
from deepeval.metrics import (
    FaithfulnessMetric,
    ContextualRecallMetric,
    AnswerRelevancyMetric,
)
from deepeval.test_case import LLMTestCase
from src.bot import CustomerSupportRAGBot

ROOT_DIR = Path(__file__).resolve().parent.parent
GOLDENS_PATH = ROOT_DIR / "data" / "synthetic_goldens.json"


@pytest.fixture(scope="module")
def synthetic_goldens():
    """Loads pre-generated synthetic goldens from data/synthetic_goldens.json."""
    assert GOLDENS_PATH.exists(), f"Synthetic dataset missing at: {GOLDENS_PATH}"
    with open(GOLDENS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


@pytest.fixture(scope="module")
def bot():
    """Live CustomerSupportRAGBot instance."""
    return CustomerSupportRAGBot()


def test_synthetic_dataset_schema_integrity(synthetic_goldens):
    """
    Schema Integrity Test (Deterministic):
    Verifies that all synthetic goldens have valid input, expected_output, and context fields.
    """
    assert len(synthetic_goldens) >= 3, "Expected at least 3 synthetic golden test cases."

    for idx, golden in enumerate(synthetic_goldens, 1):
        assert golden.get("input"), f"Golden #{idx} missing input query."
        assert golden.get("expected_output"), f"Golden #{idx} missing expected output."
        assert isinstance(golden.get("context"), list) and len(golden["context"]) > 0, (
            f"Golden #{idx} missing context list."
        )


def test_live_rag_against_synthetic_shipping_golden(bot, synthetic_goldens):
    """
    E2E Evaluation against Golden #3 (Shipping durations & costs).
    Verifies that the live RAG bot's retrieval has high contextual recall
    and that its generated output is strictly faithful to the ground truth.
    """
    # Golden #3 corresponds to shipping
    shipping_golden = next(
        g for g in synthetic_goldens
        if "shipping" in g["input"].lower()
    )

    # 1. Query live bot
    response = bot.query(shipping_golden["input"])

    # 2. Construct LLMTestCase
    test_case = LLMTestCase(
        input=shipping_golden["input"],
        actual_output=response.answer,
        expected_output=shipping_golden["expected_output"],
        retrieval_context=response.retrieved_chunks,
    )

    # 3. Evaluate faithfulness and contextual recall against synthetic ground truth
    faithfulness = FaithfulnessMetric(threshold=0.7)
    recall = ContextualRecallMetric(threshold=0.7)

    assert_test(test_case, [faithfulness, recall])


